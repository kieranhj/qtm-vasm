; player -- the two comparison players: !QTMBest (BEST=1) and !QTMOrig (BEST=0),
; built for one measured machine (build_apps.py --machine).
;
; Both are Absolutes that run in MODE 12 (24 MHz VIDC clock, so the sample rate is what
; QTM asks for) with QTM 1.49b loaded fresh by !Run, and play one of four MODs on a key.
;
; BEST=1 first patches QTM's data block. Its address is QTM's module private word
; (v1.49b stores it there: "STR R12,[R11]" in the init code), found with OS_Module 18:
;   +&1B00 linlognew   256 bytes  the load-time linear-to-log table -> identity, because
;                                 the prepared MODs already hold this machine's log codes
;   +&0380 volumetable  65 bytes  base volume table -> built from this machine's DAC
; then calls QTM_Volume 64 to rebuild the scaled volume tables from it, and sets 24 us.
; The offsets are QTM 1.49b release's (src/release/qtm_offsets.h.asm); the app ships that
; module, and kills it on exit so nothing patched outlives the app.
;
; Keys: 1-4 play a song, S stops, Q or Escape quits.

	.equ	OS_WriteC,		0x00
	.equ	OS_WriteS,		0x01
	.equ	OS_Write0,		0x02
	.equ	OS_NewLine,		0x03
	.equ	OS_ReadC,		0x04
	.equ	OS_Exit,		0x11
	.equ	OS_GetEnv,		0x10
	.equ	XOS_Byte,		0x20006
	.equ	XOS_Module,		0x2001E
	.equ	XOS_ConvertCardinal4,	0x200D8
	.equ	XQTM_Load,		0x67E40
	.equ	XQTM_Start,		0x67E41
	.equ	XQTM_Stop,		0x67E42
	.equ	XQTM_Clear,		0x67E44
	.equ	XQTM_Volume,		0x67E48
	.equ	XQTM_SetSampleSpeed,	0x67E49

	.equ	LINLOGNEW,		0x1B00
	.equ	VOLUMETABLE,		0x0380

	.org	0x8000

start:
	SWI	OS_GetEnv
	MOV	R13,R1
	MOV	R0,#22
	SWI	OS_WriteC
	MOV	R0,#12
	SWI	OS_WriteC
	LDR	R0,a_cursor_off
	MOV	R1,#10
cur:	LDRB	R2,[R0],#1
	STMFD	R13!,{R0}
	MOV	R0,R2
	SWI	OS_WriteC
	LDMFD	R13!,{R0}
	SUBS	R1,R1,#1
	BNE	cur

	LDR	R0,a_banner
	SWI	OS_Write0

	.if	BEST
	MOV	R0,#18				; find QTM's data block
	LDR	R1,a_qtm_name
	SWI	XOS_Module
	BVS	no_qtm
	CMP	R4,#0
	BEQ	no_qtm
	ADD	R5,R4,#LINLOGNEW		; identity linear-to-log table
	MOV	R0,#0
ident:	STRB	R0,[R5,R0]
	ADD	R0,R0,#1
	CMP	R0,#256
	BLT	ident
	ADD	R5,R4,#VOLUMETABLE		; this machine's volume table
	LDR	R6,a_voltab
	MOV	R0,#0
vcopy:	LDRB	R1,[R6,R0]
	STRB	R1,[R5,R0]
	ADD	R0,R0,#1
	CMP	R0,#65
	BLT	vcopy
	MOV	R0,#64
	SWI	XQTM_Volume			; rebuild the scaled tables from it
	MOV	R0,#24
	SWI	XQTM_SetSampleSpeed
	BVS	fail
	.endif

	MVN	R0,#0				; report the sample period QTM is using
	SWI	XQTM_SetSampleSpeed
	MOV	R6,R0
	SWI	OS_WriteS
	.ascii	"QTM sample period: "
	.byte	0
	.p2align 2
	MOV	R0,R6
	BL	print_number
	SWI	OS_WriteS
	.ascii	" us per frame"
	.byte	13,10,13,10
	.ascii	"  1  Push            (particles_15, Rhino)"
	.byte	13,10
	.ascii	"  2  STNICCC         (Arc-NIC10, Rhino, 6 channels)"
	.byte	13,10
	.ascii	"  3  Space Trip      (space_trip_fatman_10, Rhino)"
	.byte	13,10
	.ascii	"  4  Mikroreise      (mikroreise, Rhino)"
	.byte	13,10,13,10
	.ascii	"  S  stop    Q  quit"
	.byte	13,10,13,10,0
	.p2align 2

keys:	SWI	OS_ReadC
	BCS	quit_escape
	ORR	R0,R0,#0x20			; lower case
	CMP	R0,#0x71				; q
	BEQ	quit
	CMP	R0,#0x73				; s
	BEQ	stop
	SUB	R1,R0,#0x31			; '1'
	CMP	R1,#3
	BHI	keys
	BL	play
	B	keys

stop:	SWI	XQTM_Stop
	SWI	OS_WriteS
	.byte	13
	.ascii	"Stopped.                                        "
	.byte	0
	.p2align 2
	B	keys

play:						; R1 = song 0-3
	STMFD	R13!,{R1,R14}
	SWI	XQTM_Stop
	SWI	XQTM_Clear
	SWI	OS_WriteS
	.byte	13
	.ascii	"Loading...                                      "
	.byte	13,0
	.p2align 2
	LDMFD	R13,{R1}
	LDR	R0,a_songs
	ADD	R0,R0,R1,LSL #5			; 32-byte path slots
	MOV	R1,#0
	SWI	XQTM_Load
	BVS	load_err
	SWI	XQTM_Start
	SWI	OS_WriteS
	.ascii	"Playing song "
	.byte	0
	.p2align 2
	LDMFD	R13,{R1}
	ADD	R0,R1,#1
	BL	print_number
	SWI	OS_WriteS
	.ascii	".                                  "
	.byte	0
	.p2align 2
	LDMFD	R13!,{R1,PC}
load_err:
	ADD	R0,R0,#4			; error text
	SWI	OS_Write0
	SWI	OS_NewLine
	LDMFD	R13!,{R1,PC}

quit_escape:
	MOV	R0,#126				; acknowledge Escape
	SWI	XOS_Byte
quit:	SWI	XQTM_Stop
	SWI	XQTM_Clear
	MOV	R0,#4				; remove QTM, and with it anything we patched
	LDR	R1,a_qtm_name
	SWI	XOS_Module
	SWI	OS_Exit

	.if	BEST
no_qtm:	SWI	OS_WriteS
	.ascii	"QTMTracker is not loaded: run the app from its !Run file."
	.byte	13,10,0
	.p2align 2
	SWI	OS_ReadC
	SWI	OS_Exit
	.endif

fail:	ADD	R0,R0,#4
	SWI	OS_Write0
	SWI	OS_NewLine
	SWI	OS_ReadC
	B	quit

print_number:
	STMFD	R13!,{R0-R2,R14}
	LDR	R1,a_numbuf
	MOV	R2,#16
	SWI	XOS_ConvertCardinal4
	SWI	OS_Write0
	LDMFD	R13!,{R0-R2,PC}

a_qtm_name:	.long	qtm_name
a_banner:	.long	banner
a_songs:	.long	songs
a_cursor_off:	.long	cursor_off
a_numbuf:	.long	numbuf
	.if	BEST
a_voltab:	.long	voltab
	.endif
cursor_off:	.byte	23,1,0,0,0,0,0,0,0,0
qtm_name:	.asciz	"QTMTracker"
	.p2align 2
banner:
	.if	BEST
	.include "banner.inc"		; generated by build_apps.py: names the machine
	.else
	.ascii	"QTM as shipped: original MODs, QTM's own tables and default sample period"
	.endif
	.byte	13,10,13,10,0
	.p2align 5
songs:
	.if	BEST
	.asciz	"<QTMBest$Dir>.Push"
	.p2align 5
	.asciz	"<QTMBest$Dir>.STNICCC"
	.p2align 5
	.asciz	"<QTMBest$Dir>.SpaceTrip"
	.p2align 5
	.asciz	"<QTMBest$Dir>.Mikroreise"
	.p2align 5
	.else
	.asciz	"<QTMOrig$Dir>.Push"
	.p2align 5
	.asciz	"<QTMOrig$Dir>.STNICCC"
	.p2align 5
	.asciz	"<QTMOrig$Dir>.SpaceTrip"
	.p2align 5
	.asciz	"<QTMOrig$Dir>.Mikroreise"
	.p2align 5
	.endif
	.if	BEST
voltab:	.incbin	"voltab.bin"
	.endif
	.p2align 2
numbuf:	.skip	16

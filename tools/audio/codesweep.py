"""Test 1, the DAC code sweep: the sequence, shared by the Arc program and the analyser.

python tools/audio/codesweep.py        writes codesweep_seq.asm and codesweep.json

The Arc plays raw sound bytes in 1-channel mode at PERIOD_US per byte, so one sample is
one byte is one DAC slot. Every segment is a square wave between two codes, A and B,
switching every HALF samples; a silent segment has A = B = 0.

  1.0 s silence
  2.0 s marker: +127 / -127 at about 1 kHz, full scale  (sets the recorder gain, and with
        the end marker gives the Arc's sample rate in the recorder's clock)
  1.0 s silence
  for m = 0..127:
      0.4 s  +m against 0  at about 100 Hz    -> positive-half level of magnitude m
      0.1 s  silence
      0.4 s  -m against 0                     -> negative-half level of magnitude m
      0.1 s  silence
  2.0 s marker
  1.0 s silence

Squares against 0, not +m against -m, because the board's coupling capacitors block DC:
a symmetric square only shows the sum of the two halves, so a mismatch would be invisible.
m = 0 measures the noise floor (+0 against +0) and whether -0 differs from +0.

The byte layout is RISC OS's: bit 0 = sign (1 = negative), bits 7-1 = magnitude.
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
PERIOD_US = 48
FS = 1e6 / PERIOD_US                      # nominal; the analyser measures the real one
HALF = 104                                # 100.16 Hz
MARK_HALF = 10                            # 1041.7 Hz


def whole(seconds, half):
    """Sample count for `seconds`, rounded to whole cycles of a 2*half-sample square."""
    cyc = 2 * half
    return max(cyc, int(round(seconds * FS / cyc)) * cyc)


def code(m, negative):
    return (m << 1) | (1 if negative else 0)


def sequence():
    segs = []

    def add(kind, seconds, a, b, half, **info):
        segs.append(dict(kind=kind, count=whole(seconds, half), a=a, b=b, half=half, **info))

    add("silence", 1.0, 0, 0, HALF)
    add("marker", 2.0, code(127, False), code(127, True), MARK_HALF)
    add("silence", 1.0, 0, 0, HALF)
    for m in range(128):
        add("step", 0.4, code(m, False), 0, HALF, m=m, sign=+1)
        add("silence", 0.1, 0, 0, HALF)
        add("step", 0.4, code(m, True), 0, HALF, m=m, sign=-1)
        add("silence", 0.1, 0, 0, HALF)
    add("marker", 2.0, code(127, False), code(127, True), MARK_HALF)
    add("silence", 1.0, 0, 0, HALF)
    start = 0
    for s in segs:
        s["start"] = start
        start += s["count"]
    return segs


def write():
    segs = sequence()
    lines = [
        "; Generated by tools/audio/codesweep.py -- do not hand-edit.",
        f"; {len(segs)} segments, {segs[-1]['start'] + segs[-1]['count']} samples"
        f" at {PERIOD_US} us ({(segs[-1]['start'] + segs[-1]['count']) / FS:.1f} s).",
        "; record: count (word), code A, code B, half period (halfword)",
        f"\t.equ\tSEQ_SEGMENTS, {len(segs)}",
        f"\t.equ\tSEQ_PERIOD_US, {PERIOD_US}",
        "seq_table:",
    ]
    for s in segs:
        lines.append(f"\t.long\t{s['count']}\n\t.byte\t{s['a']}, {s['b']}, {s['half'] & 0xFF}, {s['half'] >> 8}")
    lines.append("\t.long\t0\t\t\t\t; end")
    (HERE / "arc" / "codesweep_seq.asm").write_text("\n".join(lines) + "\n", newline="\n")
    (HERE / "codesweep.json").write_text(json.dumps(dict(
        period_us=PERIOD_US, fs_nominal=FS, half=HALF, mark_half=MARK_HALF,
        segments=segs), indent=0) + "\n", newline="\n")
    total = segs[-1]["start"] + segs[-1]["count"]
    print(f"{len(segs)} segments, {total} samples, {total / FS:.1f} s")


if __name__ == "__main__":
    write()

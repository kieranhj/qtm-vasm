#!/usr/bin/env python3
"""Extract the Amiga period tables into src/shared/qtm_amiperiods.asm.

PROCinit_amiperiods assembles separately, at the fixed offset amigaperiodz and
with opt%=12 so it never reaches the golden listing.  In the module the tables
occupy the 2304 bytes that QTM_Play merely reserves with "P%+=4608/2", so the
reservation is replaced by an include of this file.

The size check at the end is not decoration: the tables are written
"DCW1712:DCW1616:..." with no space after the directive, and an earlier version
of the converter read "DCW1712" as a single identifier and silently dropped 158
of the 1152 values.  Nothing else noticed.
"""
import glob
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import bas2vasm
import dumpsyms
import variants

ROOT = Path(__file__).resolve().parent.parent
EXPECT_VALUES = 16 * 72          # 16 tuning tables of 72 notes


def main():
    variant = variants.DEFAULT
    if "--variant" in sys.argv:
        variant = sys.argv[sys.argv.index("--variant") + 1]
    dumpsyms.use(variant)
    src = [p for p in glob.glob(str(ROOT / "ref/source-text/*.bas"))
           if "v1" in Path(p).name][0]
    lines = Path(src).read_text(encoding="utf-8").split("\n")

    body, inside, started = [], False, False
    for ln in lines:
        stmt = re.sub(r"^\s*\d+ ?", "", ln)
        if stmt.startswith("DEF PROCinit_amiperiods"):
            inside = True
            continue
        if inside and stmt.startswith("ENDPROC"):
            break
        if inside and not started:
            # Skip the P%/O%/L% setup that aims the pass at amigaperiodz.
            if stmt.strip().startswith("[OPT"):
                started = True
            continue
        if started:
            body.append(ln)

    env, _, labels, _ = dumpsyms.derive()
    for name, value, _ in dumpsyms.CONFIG:
        env.setdefault(name, value)
    for name, off in labels:
        env.setdefault(name, off)

    conv = bas2vasm.Converter(env)
    conv.mode = "asm"
    out = [l for l in conv.convert(body)
           if l.strip() and not l.strip().startswith("; TODO")]
    if conv.notes:
        for note in conv.notes:
            print("unhandled: %s" % (note,), file=sys.stderr)
        return 1

    count = sum(len(l.split(".short", 1)[1].split(","))
                for l in out if ".short" in l)
    if count != EXPECT_VALUES:
        print("expected %d values, got %d" % (EXPECT_VALUES, count), file=sys.stderr)
        return 1

    header = [
        "; Amiga period tables, written at amigaperiodz by PROCinit_amiperiods.",
        "; Generated by tools/mkamiperiods.py from the driver; do not hand-edit.",
        "; %d tuning tables x 72 notes x 2 bytes = %d bytes."
        % (EXPECT_VALUES // 72, EXPECT_VALUES * 2),
        "",
    ]
    path = variants.shared_dir() / "qtm_amiperiods.asm"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(header + out) + "\n", encoding="utf-8", newline="\n")
    print("wrote %s (%d values, %d bytes)" % (path, count, count * 2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
